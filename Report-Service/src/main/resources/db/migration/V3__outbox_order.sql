-- A database sequence preserves order when application clocks repeat or move back.
ALTER TABLE report.outbox_events ADD COLUMN publication_order BIGINT GENERATED BY DEFAULT AS IDENTITY;
-- Retain historical ordering for pending rows during this additive upgrade.
UPDATE report.outbox_events SET publication_order=(
 SELECT sequence_number FROM (
  SELECT id,ROW_NUMBER() OVER (ORDER BY created_at,id) AS sequence_number FROM report.outbox_events
 ) ordered WHERE ordered.id=report.outbox_events.id
);
CREATE INDEX idx_outbox_aggregate_order ON report.outbox_events(aggregate_id,published_at,publication_order);
